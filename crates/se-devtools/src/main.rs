//! # generate-test-project
//!
//! Development tool (never shipped) behind `pnpm generate-test-project`: writes a large, valid
//! project folder to try the timeline with hundreds of items (prompt 10) and to measure
//! performance (prompt 29). Test media are generated with the bundled ffmpeg
//! (`pnpm fetch-binaries`), probed with ffprobe like a real import, and the document is built from
//! the domain types, so it always matches the current format.
//!
//! Usage: `generate-test-project [--out <folder>] [--items <count>] [--name <name>] [--seed <n>]
//! [--minutes <m>]` (defaults: `target/test-projects`, 500 items, « Projet volumineux », seed 1;
//! `--minutes 60` spreads the items over an hour, the timeline budget of `docs/performance.md`). Open the printed
//! `.seproj` folder with « Ouvrir un projet ». Thumbnails and waveforms are generated by the app
//! when the project opens.

use std::{
    io::{self, Write},
    path::{Path, PathBuf},
    process::ExitCode,
};

use se_app::{
    media_service::media_paths::relative_hint,
    ports::{MediaFiles, MediaProber, ProjectRepository},
};
use se_devtools::{DevError, media, project};
use se_domain::{Asset, AssetAnalysis, AssetId, Decodability, DerivedMedia};
use se_media::{FfprobeProber, FsMediaFiles, Tool, ToolLocator};
use se_store::FsProjectRepository;

/// Parsed command-line options.
struct Options {
    out: PathBuf,
    items: usize,
    name: String,
    seed: u64,
    /// Spread the items over this many minutes (`--minutes`), else as built.
    minutes: Option<u64>,
}

fn parse_options(mut args: impl Iterator<Item = String>) -> Result<Options, DevError> {
    let mut options = Options {
        out: PathBuf::from("target").join("test-projects"),
        items: 500,
        name: "Projet volumineux".to_owned(),
        seed: 1,
        minutes: None,
    };
    while let Some(flag) = args.next() {
        let value = args
            .next()
            .ok_or_else(|| DevError::Usage(format!("{flag} needs a value")))?;
        let number = |value: &str| {
            value
                .parse::<u64>()
                .map_err(|_| DevError::Usage(format!("{flag} expects a number, got {value}")))
        };
        match flag.as_str() {
            "--out" => options.out = PathBuf::from(value),
            "--items" => {
                options.items = usize::try_from(number(&value)?)
                    .unwrap_or(usize::MAX)
                    .max(1);
            }
            "--name" => options.name = value,
            "--seed" => options.seed = number(&value)?,
            "--minutes" => options.minutes = Some(number(&value)?.max(1)),
            other => return Err(DevError::Usage(format!("unknown option {other}"))),
        }
    }
    Ok(options)
}

/// The asset of a generated file, probed like an import.
async fn probe_asset(path: &Path, project_dir: &Path) -> Result<Asset, DevError> {
    let ffprobe = FfprobeProber::new(ToolLocator::for_current_exe(None));
    let probed = ffprobe
        .probe(path)
        .await
        .map_err(|error| DevError::Invalid(error.to_string()))?;
    let fingerprint = FsMediaFiles
        .fingerprint(path)
        .await
        .map_err(|error| DevError::Invalid(error.to_string()))?;
    let id = AssetId::from_uuid(uuid::Uuid::now_v7())
        .map_err(|error| DevError::Invalid(error.to_string()))?;
    Ok(Asset {
        id,
        original_path: path.to_string_lossy().into_owned(),
        relative_hint: relative_hint(project_dir, path),
        kind: probed.kind,
        decodability: Decodability::unchecked(&probed.info),
        media_info: Some(probed.info),
        fingerprint: Some(fingerprint),
        derived: DerivedMedia::default(),
        analysis: AssetAnalysis::default(),
        missing: false,
    })
}

async fn run(options: Options) -> Result<PathBuf, DevError> {
    std::fs::create_dir_all(&options.out).map_err(|error| DevError::io(&options.out, &error))?;
    let out =
        std::path::absolute(&options.out).map_err(|error| DevError::io(&options.out, &error))?;
    let ffmpeg = ToolLocator::for_current_exe(None)
        .locate(Tool::Ffmpeg)
        .map_err(|error| DevError::Invalid(error.to_string()))?;
    let media_dir = out.join("media");
    let project_dir = out.join(format!("{}.seproj", options.name));
    let mut assets = Vec::new();
    for path in media::generate_media(&ffmpeg, &media_dir)? {
        assets.push(probe_asset(&path, &project_dir).await?);
    }
    let mut document = project::build_project(&options.name, assets, options.items, options.seed)?;
    if let Some(minutes) = options.minutes {
        project::stretch_to(&mut document, minutes.saturating_mul(60))?;
    }
    FsProjectRepository
        .create(&out, &document)
        .await
        .map_err(|error| DevError::Invalid(error.to_string()))
}

fn report(line: &str) {
    // Nothing useful can be done if the console is gone.
    let _ = writeln!(io::stderr().lock(), "{line}");
}

fn main() -> ExitCode {
    let options = match parse_options(std::env::args().skip(1)) {
        Ok(options) => options,
        Err(error) => {
            report(&error.to_string());
            return ExitCode::FAILURE;
        }
    };
    let items = options.items;
    let runtime = match tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
    {
        Ok(runtime) => runtime,
        Err(error) => {
            report(&format!("cannot start the async runtime: {error}"));
            return ExitCode::FAILURE;
        }
    };
    match runtime.block_on(run(options)) {
        Ok(path) => {
            report(&format!(
                "generate-test-project: {items} items written to {}",
                path.display()
            ));
            ExitCode::SUCCESS
        }
        Err(error) => {
            report(&format!("generate-test-project: {error}"));
            ExitCode::FAILURE
        }
    }
}
